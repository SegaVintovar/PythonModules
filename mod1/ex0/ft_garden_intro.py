def main() -> None:
    """Very first Python program that displays information about a
    plant in your garden"""
    print('=== Welcome to My Garden ===')
    plant: str = 'Rose'
    height: str = '25cm'
    age: str = '30 days'
    print('Plant: ', plant, '\nHeight: ', height, '\nAge: ', age)
    print('\n=== End of Program ===')


if __name__ == "__main__":
    main()
